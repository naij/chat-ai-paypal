import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const browser = await chromium.launch({headless:true,...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
try {
  const page = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await page.addInitScript(() => localStorage.setItem('xtoken', 'test-auth')); 
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.BASE_URL || 'http://localhost:8080');
  await page.getByRole('heading',{name:'Aria Chen',exact:true}).waitFor();
  await page.getByRole('button',{name:'Open Chat AI'}).click();
  assert.equal(new URL(page.url()).hash, '#/chat');
  await page.getByRole('button',{name:'I want to hire someone',exact:true}).click();
  assert.equal(await page.locator('#app').getAttribute('data-intent'), 'earn');
  await page.getByRole('link',{name:'Open profile'}).click();
  await page.getByRole('heading',{name:'Aria Chen',exact:true}).waitFor();
  await mkdir('test-results',{recursive:true});
  await page.screenshot({path:'test-results/profile.png'});
  await page.getByRole('button',{name:'Open wallet',exact:true}).click();
  assert.ok((await page.locator('.profile-dialog').textContent()).includes('6,980,999'));
  await page.getByRole('button',{name:'Close panel'}).click();
  await page.getByRole('button',{name:'Profile options'}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Display name').fill('Aria Chen Demo');
  await page.getByRole('button',{name:'Save changes'}).click();
  await page.getByRole('heading',{name:'Aria Chen Demo',exact:true}).waitFor();
  await page.getByRole('button',{name:'Task management',exact:true}).click();
  await page.getByRole('button',{name:'Poll',exact:true}).click();
  assert.ok((await page.locator('.profile-dialog').textContent()).includes('Where should we meet next?'));
  await page.getByRole('button',{name:'Close panel'}).click();
  await page.getByRole('button',{name:'Properties',exact:true}).first().click();
  assert.equal(await page.locator('.profile-dialog .profile-detail-row').count(),3);
  await page.getByRole('button',{name:'Close panel'}).click();
  await page.getByRole('button',{name:'Posts',exact:true}).click();
  assert.equal(await page.locator('.profile-post').count(),3);
  await page.getByRole('button',{name:'Close panel'}).click();
  await page.getByRole('button',{name:'Gallery',exact:true}).click();
  assert.equal(await page.locator('.profile-gallery figure').count(),3);
  await page.getByRole('button',{name:'Close panel'}).click();
  await page.locator('.profile-scroll').evaluate(el=>el.scrollTop=0);
  await page.getByRole('link',{name:'Back to Chat AI'}).click();
  await page.getByRole('button',{name:'I want to hire someone',exact:true}).click();
  assert.equal(await page.locator('#app').getAttribute('data-intent'), 'earn');
  await page.waitForFunction(()=>document.querySelector('#app').dataset.stage==='boss-ready');
  await page.locator('#send').click();
  await page.waitForFunction(()=>document.querySelector('#app').dataset.stage==='boss-candidates' && !document.querySelector('#send').disabled);
  await page.locator('#more').click();
  await page.getByRole('link',{name:'Profile',exact:true}).click();
  await page.getByRole('link',{name:'Back to Chat AI'}).click();
  await page.getByRole('button',{name:'I want to hire someone',exact:true}).click();
  assert.equal(await page.locator('#app').getAttribute('data-intent'), 'earn');
  assert.equal(await page.locator('.hire-task').count(),3);
  await page.goto((process.env.BASE_URL || 'http://localhost:8080')+'/#/profile');
  for(const width of [320,430,1440]) {
    await page.setViewportSize({width,height:900});
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await page.locator('.profile-page img').evaluateAll(imgs=>imgs.every(img=>img.complete && img.naturalWidth>0)),true);
  }
  assert.deepEqual(errors,[]);
  console.log('Profile checks passed: sample data, menus, edit, collections, direct link, chat preservation, responsive layouts and local images.');
} finally {await browser.close();}
